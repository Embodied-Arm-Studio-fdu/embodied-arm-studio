#!/usr/bin/env python3
"""Initialize and operate an isolated, portable self-hosted Studio deployment."""
import argparse
import ipaddress
import json
import os
from pathlib import Path
import platform
import re
import secrets
import shutil
import stat
import subprocess
import sys
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CONFIG = ROOT / '.env.selfhost'


def read_config(path):
    path = Path(path)
    if path.is_symlink() or not path.is_file():
        raise ValueError('Configuration must be an existing regular file; run init first')
    if os.name == 'posix' and stat.S_IMODE(path.stat().st_mode) & 0o077:
        raise ValueError('Private configuration must have mode 0600: chmod 600 your-config-file')
    result = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        key, separator, value = line.partition('=')
        if not separator or not re.fullmatch(r'[A-Z][A-Z0-9_]*', key):
            raise ValueError('Invalid environment-file entry')
        if key in result:
            raise ValueError('Duplicate environment-file key: ' + key)
        if value.startswith("'") and value.endswith("'"):
            value = value[1:-1].replace("\\'", "'")
        elif value.startswith('"') and value.endswith('"'):
            value = json.loads(value)
        result[key] = value
    return result


def validate_config(values):
    source = values.get('STUDIO_IMAGE_SOURCE', 'build')
    if source not in ('build', 'prebuilt'):
        raise ValueError('STUDIO_IMAGE_SOURCE must be build or prebuilt')
    if source == 'prebuilt':
        roles = ['API', 'WEB'] + (['SIMULATION', 'WORKER'] if values.get('STUDIO_DEPLOY_MODE') == 'gpu' else [])
        for role in roles:
            if not re.fullmatch(r'[a-zA-Z0-9][a-zA-Z0-9._:/-]*@sha256:[a-f0-9]{64}', values.get('STUDIO_IMAGE_' + role, '')):
                raise ValueError('Prebuilt images require a release digest: ' + role)
    if values.get('STUDIO_DEPLOY_MODE') not in ('core', 'gpu'):
        raise ValueError('STUDIO_DEPLOY_MODE must be core or gpu')
    if not re.fullmatch(r'[a-z0-9][a-z0-9_-]*', values.get('STUDIO_PROJECT_NAME', '')):
        raise ValueError('Invalid STUDIO_PROJECT_NAME')
    for key in ('POSTGRES_PASSWORD', 'USER_JWT_SECRET', 'SIMULATION_SERVICE_TOKEN', 'INTERNAL_RUN_EVENT_SERVICE_TOKEN'):
        if not re.fullmatch(r'[a-f0-9]{48,}', values.get(key, '')):
            raise ValueError(key + ' must be generated by init (hex, at least 24 bytes)')
    port = values.get('STUDIO_HTTP_PORT', '')
    if not port.isdigit() or not 1 <= int(port) <= 65535:
        raise ValueError('Invalid STUDIO_HTTP_PORT')
    if ipaddress.ip_address(values.get('STUDIO_BIND_ADDRESS', '')).version != 4:
        raise ValueError('STUDIO_BIND_ADDRESS currently requires an IPv4 address')
    if values['STUDIO_DEPLOY_MODE'] == 'gpu':
        ports = {}
        for key, default in (('STUDIO_MEDIA_HTTP_PORT', '18889'), ('STUDIO_MEDIA_UDP_PORT', '18189'), ('STUDIO_MEDIA_TCP_PORT', '18191')):
            value = values.get(key, default)
            if not value.isdigit() or not 1 <= int(value) <= 65535:
                raise ValueError('Invalid ' + key)
            ports[key] = int(value)
        tcp_ports = [int(port), ports['STUDIO_MEDIA_HTTP_PORT'], ports['STUDIO_MEDIA_TCP_PORT']]
        if len(set(tcp_ports)) != len(tcp_ports):
            raise ValueError('Web, Media HTTP and ICE TCP ports must differ')
        if values.get('STUDIO_MEDIA_UDP_ADDRESS', ':' + str(ports['STUDIO_MEDIA_UDP_PORT'])) not in ('', ':' + str(ports['STUDIO_MEDIA_UDP_PORT'])):
            raise ValueError('STUDIO_MEDIA_UDP_ADDRESS must be empty or match the UDP port')
        loopback = values.get('STUDIO_ALLOW_LOOPBACK_PLAYBACK', '0')
        if loopback not in ('0', '1'):
            raise ValueError('STUDIO_ALLOW_LOOPBACK_PLAYBACK must be 0 or 1')
        allow_loopback = loopback == '1'
        if allow_loopback and not ipaddress.ip_address(values['STUDIO_BIND_ADDRESS']).is_loopback:
            raise ValueError('SSH playback requires a loopback bind address')
        host = values.get('STUDIO_PUBLIC_HOST', '')
        if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9.-]*', host) or (host.lower() == 'localhost' and not allow_loopback):
            raise ValueError('GPU mode requires a LAN IPv4 address or DNS host, without a URL or port')
        try:
            if (ipaddress.ip_address(host).is_loopback and not allow_loopback) or ipaddress.ip_address(host).is_unspecified:
                raise ValueError('STUDIO_PUBLIC_HOST must be reachable by the browser, not loopback/unspecified')
        except ValueError as exc:
            if re.fullmatch(r'[0-9.]+', host) or 'reachable' in str(exc):
                raise
        for key in ('STUDIO_WEB_ORIGIN', 'STUDIO_STREAM_ORIGIN'):
            url = urlsplit(values.get(key, ''))
            if url.scheme not in ('http', 'https') or url.hostname != host or url.port is None or url.path not in ('', '/') or url.query or url.fragment or url.username or url.password:
                raise ValueError(key + ' must be an origin with the public host and explicit port')
        if urlsplit(values['STUDIO_WEB_ORIGIN']).port != int(port):
            raise ValueError('STUDIO_WEB_ORIGIN must match STUDIO_HTTP_PORT')
        if urlsplit(values['STUDIO_STREAM_ORIGIN']).port != ports['STUDIO_MEDIA_HTTP_PORT']:
            raise ValueError('STUDIO_STREAM_ORIGIN must match STUDIO_MEDIA_HTTP_PORT')
        try:
            from scripts.reference_models import validate_models
        except ModuleNotFoundError:
            from reference_models import validate_models
        validate_models(values.get('REFERENCE_MODELS_PATH', ''))
        for key, suffix in (('ISAAC_GYM_PATH', 'python/isaacgym/_bindings/linux-x86_64/gym_38.so'), ('S1_ASSETS_PATH', 'urdf/yhrg_s1_v2.urdf')):
            value = values.get(key, '')
            if not value or not Path(value).is_absolute() or not (Path(value) / suffix).is_file():
                raise ValueError(key + ' must be an absolute directory containing ' + suffix)


def initialize(path, mode='core', public_host='', sdk='', assets='', bind='127.0.0.1', port=8080, project='embodied-arm-selfhost', media_http_port=18889, media_udp_port=18189, media_tcp_port=18191, allow_loopback_playback=False):
    if Path(path).exists() or Path(path).is_symlink():
        existing = read_config(path)
        if existing.get('STUDIO_DEPLOY_MODE') != mode:
            raise ValueError('Existing configuration uses another mode; use its original configuration')
        validate_config(existing)
        print('Reusing existing private configuration without changing credentials: ' + str(path))
        return existing
    model_root = ''
    if mode == 'gpu':
        try:
            from scripts.reference_models import prepare_models
        except ModuleNotFoundError:
            from reference_models import prepare_models
        model_root = str(prepare_models(ROOT / 'external/reference-models'))
    values = {
        'STUDIO_DEPLOY_MODE': mode, 'STUDIO_PROJECT_NAME': project,
        'STUDIO_BIND_ADDRESS': bind, 'STUDIO_HTTP_PORT': str(port),
        'STUDIO_PUBLIC_HOST': public_host, 'STUDIO_WEB_ORIGIN': 'http://%s:%s' % (public_host or 'localhost', port),
        'STUDIO_STREAM_ORIGIN': 'http://%s:%s' % (public_host or 'localhost', media_http_port),
        'REFERENCE_MODELS_PATH': model_root,
        'STUDIO_GPU_DEVICE': '0', 'ISAAC_GYM_PATH': str(Path(sdk).expanduser().resolve()) if sdk else '',
        'S1_ASSETS_PATH': str(Path(assets).expanduser().resolve()) if assets else '',
        'OPENAI_API_KEY': '', 'OPENAI_MODEL': '', 'OPENAI_BASE_URL': 'https://api.openai.com/v1',
        'DEEPSEEK_API_KEY': '', 'DEEPSEEK_MODEL': '', 'ANTHROPIC_API_KEY': '', 'ANTHROPIC_MODEL': '',
    }
    if mode == 'gpu':
        values['STUDIO_MEDIA_HTTP_PORT'] = str(media_http_port)
        values['STUDIO_MEDIA_UDP_PORT'] = str(media_udp_port)
        values['STUDIO_MEDIA_TCP_PORT'] = str(media_tcp_port)
        values['STUDIO_MEDIA_UDP_ADDRESS'] = '' if allow_loopback_playback else ':' + str(media_udp_port)
        values['STUDIO_ALLOW_LOOPBACK_PLAYBACK'] = '1' if allow_loopback_playback else '0'
    for key in ('POSTGRES_PASSWORD', 'USER_JWT_SECRET', 'SIMULATION_SERVICE_TOKEN', 'INTERNAL_RUN_EVENT_SERVICE_TOKEN'):
        values[key] = secrets.token_hex(48)
    validate_config(values)
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    # O_EXCL also refuses symlinks and preserves existing deployment credentials.
    descriptor = os.open(str(path), os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, 'w') as target:
        target.write('# Private self-hosting configuration. Never commit this file.\n')
        for key, value in values.items():
            if '\n' in value or '\r' in value:
                raise ValueError('Multiline environment values are not supported')
            target.write(key + "='" + value.replace("'", "\\'") + "'\n")
    print('Created private configuration: ' + str(path))
    print('Mode: ' + mode + '. Next: doctor, up, bootstrap.')
    return values


def compose_command(config_path, values):
    command = ['docker', 'compose', '--project-directory', str(ROOT / 'deploy'), '--project-name', values['STUDIO_PROJECT_NAME'], '--env-file', str(Path(config_path).resolve()), '-f', str(ROOT / 'deploy/compose.yaml')]
    if values['STUDIO_DEPLOY_MODE'] == 'gpu':
        command += ['-f', str(ROOT / 'deploy/compose.gpu.yaml')]
    if values.get('STUDIO_IMAGE_SOURCE') == 'prebuilt':
        command += ['-f', str(ROOT / 'deploy/compose.images.yaml')]
        if values['STUDIO_DEPLOY_MODE'] == 'gpu':
            command += ['-f', str(ROOT / 'deploy/compose.images.gpu.yaml')]
    return command


def compose_environment():
    # Do not let inherited variables silently replace this deployment's secrets,
    # SDK paths, or Compose project selection.
    result = dict(os.environ)
    for key in list(result):
        if key.startswith(('STUDIO_', 'SIMULATION_', 'COMPOSE_', 'OPENAI_', 'DEEPSEEK_', 'ANTHROPIC_')) or key in ('POSTGRES_PASSWORD', 'USER_JWT_SECRET', 'INTERNAL_RUN_EVENT_SERVICE_TOKEN', 'ISAAC_GYM_PATH', 'S1_ASSETS_PATH', 'REFERENCE_MODELS_PATH'):
            result.pop(key)
    return result


def doctor(config_path, values, offline=False):
    validate_config(values)
    if values['STUDIO_DEPLOY_MODE'] == 'gpu' and (platform.system() != 'Linux' or platform.machine() not in ('x86_64', 'AMD64')):
        raise ValueError('The GPU worker requires a Linux x86_64 NVIDIA host')
    if offline:
        print('Offline configuration checks passed; Docker, GPU and services have not been tested.')
        return
    if shutil.which('docker') is None:
        raise ValueError('Install Docker Engine and the Docker Compose v2 plugin first')
    version = subprocess.check_output(['docker', 'compose', 'version', '--short'], text=True, env=compose_environment()).strip()
    numbers = re.search(r'(\d+)\.(\d+)', version)
    if not numbers or tuple(map(int, numbers.groups())) < (2, 20):
        raise ValueError('Docker Compose 2.20 or newer is required')
    print('Docker Compose ' + version)
    subprocess.run(['docker', 'info', '--format', '{{.ServerVersion}}'], check=True, env=compose_environment())
    subprocess.run(compose_command(config_path, values) + ['config', '--quiet'], check=True, env=compose_environment())
    if values['STUDIO_DEPLOY_MODE'] == 'gpu':
        if shutil.which('nvidia-smi') is None:
            raise ValueError('NVIDIA driver/nvidia-smi is missing; install a compatible driver yourself. No system changes were made.')
        runtimes = json.loads(subprocess.check_output(['docker', 'info', '--format', '{{json .Runtimes}}'], text=True, env=compose_environment()))
        if 'nvidia' not in runtimes:
            raise ValueError('NVIDIA Container Toolkit runtime is missing; configure Docker GPU access yourself. No system changes were made.')
        subprocess.run(['nvidia-smi', '--query-gpu=name,driver_version', '--format=csv,noheader'], check=True)
        print('GPU container access, SDK import and NVENC are checked again by gpu-check and the worker entrypoint.')
    print('Host and Compose configuration checks passed.')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, default=DEFAULT_CONFIG)
    commands = parser.add_subparsers(dest='command', required=True)
    init = commands.add_parser('init')
    init.add_argument('--mode', choices=['core', 'gpu'], default='core')
    init.add_argument('--public-host', default='')
    init.add_argument('--isaac-gym-path', default='')
    init.add_argument('--s1-assets-path', default='')
    init.add_argument('--bind', default='127.0.0.1')
    init.add_argument('--port', type=int, default=8080)
    init.add_argument('--project', default='embodied-arm-selfhost')
    init.add_argument('--media-http-port', type=int, default=18889)
    init.add_argument('--media-udp-port', type=int, default=18189)
    init.add_argument('--media-tcp-port', type=int, default=18191)
    init.add_argument('--allow-loopback-playback', action='store_true',
                      help='Explicit SSH/localhost video mode; requires a loopback bind')
    check = commands.add_parser('doctor')
    check.add_argument('--offline', action='store_true')
    for name in ('up', 'status', 'logs', 'down', 'gpu-check'):
        commands.add_parser(name)
    seed = commands.add_parser('bootstrap')
    seed.add_argument('--namespace', default='studio')
    args = parser.parse_args(argv)
    try:
        if args.command == 'init':
            initialize(args.config, args.mode, args.public_host, args.isaac_gym_path, args.s1_assets_path, args.bind, args.port, args.project, args.media_http_port, args.media_udp_port, media_tcp_port=args.media_tcp_port, allow_loopback_playback=args.allow_loopback_playback)
            return 0
        values = read_config(args.config)
        if args.command in ('up', 'doctor'):
            doctor(args.config, values, getattr(args, 'offline', False))
        else:
            # status/down must still work if a previously mounted SDK is absent.
            if values.get('STUDIO_DEPLOY_MODE') not in ('core', 'gpu') or not re.fullmatch(r'[a-z0-9][a-z0-9_-]*', values.get('STUDIO_PROJECT_NAME', '')):
                raise ValueError('Invalid deployment identity')
        if args.command == 'doctor':
            return 0
        command = compose_command(args.config, values)
        if args.command == 'up':
            command += ['up'] + (['--no-build', '--pull', 'always'] if values.get('STUDIO_IMAGE_SOURCE') == 'prebuilt' else ['--build']) + ['-d', '--wait', '--wait-timeout', '600']
        elif args.command == 'bootstrap':
            if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', args.namespace) or len(args.namespace) > 48:
                raise ValueError('Invalid bootstrap namespace')
            command += ['run', '--rm'] + (['--no-build'] if values.get('STUDIO_IMAGE_SOURCE') == 'prebuilt' else []) + (['-it'] if sys.stdin.isatty() else []) + ['--no-deps', 'bootstrap', 'python', '-m', 'scripts.bootstrap_self_host', '--namespace', args.namespace, '--apply']
        elif args.command == 'gpu-check':
            if values['STUDIO_DEPLOY_MODE'] != 'gpu':
                raise ValueError('gpu-check requires a GPU deployment configuration')
            validate_config(values)
            command += ['run', '--rm'] + (['--no-build'] if values.get('STUDIO_IMAGE_SOURCE') == 'prebuilt' else []) + ['--no-deps', 'gpu-check']
        else:
            command += {'status': ['ps'], 'logs': ['logs', '--tail', '100', '-f'], 'down': ['down']}[args.command]
        subprocess.run(command, check=True, env=compose_environment())
        if args.command == 'up':
            print('Studio: ' + values['STUDIO_WEB_ORIGIN'] + '. Create users/course with bootstrap.')
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        # Do not echo subprocess argument values or environment-file contents.
        print('Self-hosting command failed: ' + (str(exc) if not isinstance(exc, subprocess.CalledProcessError) else 'a required command returned a nonzero status'), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
